const fs=require('fs');
const read=f=>fs.existsSync(f)?fs.readFileSync(f,'utf8'):'';
const fail=[];
const index=read('index.html'),sw=read('sw.js'),pwa=read('pwa-update.js'),settings=read('settings-ui.js'),manifest=read('manifest.json'),workflow=read('.github/workflows/pages.yml');
function need(src,pattern,msg){if(!pattern.test(src))fail.push(msg)}
need(index,/pwa-update\.css/,'index.html must load pwa-update.css');
need(index,/build-info\.js/,'index.html must load generated build-info.js');
need(index,/pwa-update\.js/,'index.html must load pwa-update.js');
need(manifest,/"display"\s*:\s*"standalone"/,'manifest must remain standalone-installable');
need(manifest,/"start_url"/,'manifest must define start_url');
need(sw,/BUILD_ID='__SAKHI_BUILD_ID__'/,'service worker cache name must be stamped from build id');
need(sw,/const CACHE='sakhi-magic-learning-'\+BUILD_ID/,'service worker cache name must include build version');
need(sw,/SKIP_WAITING[\s\S]{0,120}skipWaiting\(\)/,'service worker must handle SKIP_WAITING');
need(sw,/clients\.claim\(\)/,'service worker activation must claim clients');
need(sw,/deleteOldSakhiCaches/,'service worker must delete old Sakhi caches');
need(sw,/url\.origin===self\.location\.origin/,'service worker must restrict runtime caching to same-origin app assets');
need(sw,/cache:'no-store'/,'index/version/sw/manifest requests must use no-store revalidation behavior');
if(/install[\s\S]{0,180}skipWaiting\(\)/.test(sw))fail.push('service worker must not automatically skipWaiting during install; update banner must control activation');
need(pwa,/navigator\.serviceWorker\.register\('\.\/sw\.js'\)/,'client must register ./sw.js');
need(pwa,/checkForUpdate\(registration\)/,'client must call update check on startup');
need(pwa,/registration\.update\(\)/,'client must call registration.update()');
need(pwa,/registration\.waiting/,'client must detect waiting worker');
need(pwa,/updatefound/,'client must listen for updatefound');
need(pwa,/controllerchange/,'client must listen for controllerchange');
need(pwa,/Refresh now/,'update banner must include Refresh now');
need(pwa,/Later/,'update banner must include Later');
need(pwa,/refreshRequested/,'controllerchange reload must be gated by explicit refresh request');
need(pwa,/reloadCount/,'client must track reload count to avoid loops');
need(pwa,/display-mode: standalone/,'client must detect standalone display mode');
need(pwa,/Add to Home Screen/,'client must include iPhone/iPad Add to Home Screen guidance');
need(pwa,/version\.json/,'client must fetch version.json with revalidation');
need(settings,/Developer Information/,'Parent Settings must expose Developer Information');
need(settings,/data-build-id/,'Parent Settings must show current build ID');
need(settings,/Installed on this device/,'Parent Settings must show installed device status');
need(settings,/Add to Home Screen/,'Parent Settings must show iPhone/iPad installation guidance');
need(settings,/Test Sakhi Sound/,'Parent Settings must provide a test Sakhi sound button');
need(workflow,/build-info\.js/,'deployment must generate build-info.js');
need(workflow,/version\.json/,'deployment must generate version.json');
need(workflow,/__SAKHI_BUILD_ID__/,'deployment must stamp service worker build id');
need(workflow,/validate-pwa-update\.cjs/,'deployment must run PWA update validator');
if(fail.length){console.error('PWA update validation failed:\n- '+fail.join('\n- '));process.exit(1)}
console.log('PWA update validation passed: install guidance, explicit update banner, build metadata, no-cache revalidation behavior, and cache cleanup are wired.');
